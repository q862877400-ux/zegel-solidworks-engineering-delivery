def patch(path: Path, old: str, new: str, label: str) -> bool:
    text = path.read_text(encoding="utf-8")
    if old not in text:
        print(f"  [skip] {label}: 未匹配")
        return False
    path.write_text(text.replace(old, new), encoding="utf-8")
    print(f"  [ok]   {label}")
    return True


